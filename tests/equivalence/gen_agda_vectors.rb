# frozen_string_literal: true

# Writes agda/Spiral/Vectors.agda from the Ruby spiral engine's output, so that Agda's type checker
# confirms (by evaluation, refl) that the Agda-defined spiral equals the Ruby/CBQN closed-form
# spiral on these indices. Run: ruby tests/equivalence/gen_agda_vectors.rb
require_relative '../../ruby/application/spiral'

N = 81
def agda_int(v) = v.negative? ? "-[1+ #{-v - 1} ]" : "(+ #{v})"

positions = (0...N).map { |i| MorphicHelix::Spiral.position(i) }
list = positions.map { |x, y| "(#{agda_int(x)} , #{agda_int(y)})" }.join(" ∷\n  ") + " ∷ []"
header = File.read(File.join(__dir__, '..', '..', 'agda', 'Prelude.agda')).lines.first(2).join
out = <<~AGDA
  #{header.chomp}
  {-# OPTIONS --safe --without-K #-}
  -- GENERATED by tests/equivalence/gen_agda_vectors.rb from ruby/application/spiral.rb.
  -- Cross-language check: the Agda spiral (Spiral.Index.position, defined by ring enumeration)
  -- evaluates to exactly the Ruby closed-form positions for indices 0..#{N - 1}, and the ring offsets
  -- `before k` equal (2k+1)² used by the Ruby and CBQN closed forms.
  module Spiral.Vectors where

  open import Prelude
  open import Spiral.Index

  map : {A B : Set} → (A → B) → List A → List B
  map f [] = []
  map f (x ∷ xs) = f x ∷ map f xs

  upto : Nat → List Nat
  upto n = count n []
    where
      count : Nat → List Nat → List Nat
      count zero acc = acc
      count (suc m) acc = count m (m ∷ acc)

  ruby-positions : List Coord
  ruby-positions =
    #{list}

  agrees-with-ruby : map position (upto #{N}) ≡ ruby-positions
  agrees-with-ruby = refl

  indices-recovered : map index ruby-positions ≡ upto #{N}
  indices-recovered = refl

  before-squares : map before (upto 6) ≡ #{(0...6).map { |k| (2 * k + 1)**2 }.join(' ∷ ')} ∷ []
  before-squares = refl
AGDA
File.write(File.join(__dir__, '..', '..', 'agda', 'Spiral', 'Vectors.agda'), out)
puts "wrote agda/Spiral/Vectors.agda with #{N} positions"
