# Runs every verification step. Each step's full output goes to evidence/verification/logs/<step>.log and a
# row "step<TAB>expect<TAB>exit<TAB>outcome<TAB>log<TAB>command" is appended to evidence/verification/checks.tsv.
# Steps marked "fail" are negative controls: they MUST exit non-zero AND their log must contain the stated
# failure text, so a control that fails for an unrelated reason (missing file, crash, missing tool) is
# reported as UNEXPECTED. Failing output is kept. Exit 1 if any step's outcome differs from its expectation;
# a missing tool makes the first step fail with "missing <tool>". No step can be skipped.
#   scripts/verify-all.sh
set -u
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"
V=evidence/verification
rm -rf "$V/logs" && mkdir -p "$V/logs"   # no log from an earlier run survives
TSV="$V/checks.tsv"
printf 'step\texpect\texit\toutcome\tlog\tcommand\n' >"$TSV"
bad=0
JAR=${MH_ALLOY_JAR:-/opt/toolchains/org.alloytools.alloy.dist.jar}

check() {
  name=$1; expect=$2; shift 2
  pattern=""
  if [ "$expect" = fail ]; then pattern=$1; shift; fi
  log="$V/logs/$name.log"
  { echo "\$ $*"; echo "# started $(date '+%Y-%m-%dT%H:%M:%S%z')"; } >"$log"
  sh -c "$*" >>"$log" 2>&1
  code=$?
  echo "# exit $code" >>"$log"
  if [ "$expect" = pass ] && [ $code -eq 0 ]; then outcome=as-expected
  elif [ "$expect" = fail ] && [ $code -ne 0 ] && grep -qF -- "$pattern" "$log"; then outcome=as-expected
  else outcome=UNEXPECTED; bad=1; fi
  [ "$expect" = fail ] && echo "# required failure text: $pattern" >>"$log"
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$name" "$expect" "$code" "$outcome" "$log" "$*" >>"$TSV"
  printf '%-34s expect=%-4s exit=%-3s %s\n' "$name" "$expect" "$code" "$outcome"
}

check tools pass "scripts/require-tool.sh ruby node bqn twelf-server agda java Xvfb import openbox xdotool wmctrl pgrep && test -f '$JAR' || { echo 'missing alloy jar $JAR'; exit 127; }"
check versions pass "ruby --version && node --version && agda --version && java -version 2>&1 && echo quit | twelf-server | head -1 && readlink -f \$(command -v bqn) && git -C /opt/toolchains/CBQN rev-parse HEAD && java -jar '$JAR' version 2>&1 | head -3"
check policy pass "ruby scripts/check_policy.rb"
check ruby-syntax pass "for f in \$(find ruby tests scripts -name '*.rb'); do ruby -c \$f >/dev/null || exit 1; done; echo all ruby files Syntax OK"
check original-js-main pass "node source/original-archive/pristine/fibonacci_braid/fibonacci_braid.js"
check regression pass "ruby tests/regression/test_regression.rb"
check vectors-deterministic pass "cp tests/equivalence/vectors.json /tmp/mh-vectors.\$\$ && ruby tests/equivalence/gen_vectors.rb && cmp /tmp/mh-vectors.\$\$ tests/equivalence/vectors.json && echo vectors.json regenerated byte-identically"
check agda-vectors-deterministic pass "cp agda/Spiral/Vectors.agda /tmp/mh-av.\$\$ && ruby tests/equivalence/gen_agda_vectors.rb && cmp /tmp/mh-av.\$\$ agda/Spiral/Vectors.agda && echo Vectors.agda regenerated byte-identically"
check properties pass "ruby tests/properties/test_properties.rb"
check equivalence pass "ruby tests/equivalence/test_equivalence.rb"
check agda-everything pass "rm -rf agda/_build && cd agda && agda Everything.agda"
agda_negative() { check "agda-negative-$1" fail "$2" "rm -rf tests/properties/agda-negative/_build && cd tests/properties/agda-negative && agda $1.agda"; }
agda_negative WrongStepCount '9 != 11 of type Nat'
agda_negative PostulateRejected 'Cannot postulate'
agda_negative InvolutionFalse 'xorV x y != x of type Vec Bool 1'
check elf-signature pass "scripts/elf-check.sh"
for f in tests/properties/elf-negative/*.elf; do
  b=$(basename "$f" .elf)
  check "elf-negative-$b" fail 'Coverage error --- missing cases:' "scripts/elf-check.sh $f"
done
check alloy pass "ruby scripts/alloy-check.rb"
check integration pass "ruby tests/integration/test_integration.rb"
check missing-tool-fails-closed fail 'missing bqn' "env PATH=/nonexistent /usr/bin/sh scripts/require-tool.sh bqn"
check missing-tool-adapter fail 'missing bqn (MorphicHelix::MissingTool)' "MH_BQN=/nonexistent/bqn ruby -e 'require \"./ruby/adapters/cbqn_adapter\"; MorphicHelix::CBQNAdapter.new.call(\"fibs\", 5)'"
check gui-screenshots pass "scripts/gui-screenshots.sh"
check gui-close pass "scripts/gui-close-test.sh"
check manifests pass "ruby scripts/build_manifests.rb"
echo "checks: $TSV"
exit $bad
